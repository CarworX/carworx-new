# Builds public/intro/intro.js from the approved motion export
# planning/design/brand/exports/motion/carworx-hero-embed.html (verbatim engine)
# plus the first-visit wrapper (owner, 14 Nov 2026). Run from the repo root:
#   python3 apps/web/scripts/intro/build.py
import re
SRC = "planning/design/brand/exports/motion/carworx-hero-embed.html"
s = open(SRC, encoding="utf-8").read()
body = re.search(r"<script>(.*?)</script>", s, flags=re.S).group(1)
engine = body[: body.index("const el = document.getElementById('s');")]
# The data line `const S = scene(...)` stays; only the cut is chosen below.
engine = engine.replace("{ w: 1920, h: 1080, bg: true, cut: 'hero' });", "INTRO_OPTS);")
assert "INTRO_OPTS" in engine
# A ~3 s cut of the same beat sheet: beams, turbine, wordmark, then the fade.
engine = engine.replace("  splash: { duration: 1.6 },", "  splash: { duration: 1.6 },\n  intro: { duration: 2.55 },")
engine = engine.replace(
    "function heroTime(S, t) {\n",
    "function heroTime(S, t) {\n  if (S.cut === 'intro') return Math.min(6.25, t * (6.25 / 2.55));\n",
)
assert "intro: { duration" in engine and "S.cut === 'intro'" in engine
head = """// GENERATED by apps/web/scripts/intro/build.py from
// planning/design/brand/exports/motion/carworx-hero-embed.html (engine verbatim).
// First-visit intro: plays once per browser (localStorage), never with reduced
// motion, skips on any tap, click, scroll or key, and only covers the page:
// without JavaScript nothing here runs and the page simply shows.
(() => {
  const KEY = 'cx-intro-seen';
  try { if (localStorage.getItem(KEY)) return; } catch { return; }
  if (matchMedia('(prefers-reduced-motion: reduce)').matches) return;
  try { localStorage.setItem(KEY, '1'); } catch { return; }
  const vw = innerWidth || 1280, vh = innerHeight || 800;
  const W = vw / vh < 1 ? 1640 : Math.max(1400, Math.round(1080 * vw / vh));
  const H = vw / vh < 1 ? Math.round(1640 * vh / vw) : 1080;
  const INTRO_OPTS = { w: W, h: H, bg: true, cut: 'intro' };
  // The container is rendered (hidden) by routes/home.tsx just before this script.
  const el = document.getElementById('cx-intro');
  if (!el) return;
  el.style.cssText = 'position:fixed;inset:0;z-index:2147483000;background:#0d0f12;display:grid;place-items:center;cursor:pointer;transition:opacity .45s ease';
  el.hidden = false;
"""
tail = """
  el.innerHTML = '';
  const host = document.createElement('div');
  host.style.cssText = 'width:100%;height:100%';
  el.appendChild(host);
  let done = false, raf = 0;
  const close = (fast) => {
    if (done) return; done = true; cancelAnimationFrame(raf);
    el.style.transitionDuration = fast ? '.2s' : '.45s';
    el.style.opacity = '0';
    setTimeout(() => { el.hidden = true; el.innerHTML = ''; el.style.cssText = ''; }, fast ? 220 : 470);
    for (const e of ['pointerdown', 'keydown', 'wheel', 'touchstart']) removeEventListener(e, skip, true);
  };
  const skip = () => close(true);
  for (const e of ['pointerdown', 'keydown', 'wheel', 'touchstart']) addEventListener(e, skip, { capture: true, passive: true });
  const draw = (t) => {
    host.innerHTML = frame(S, Math.min(t, S.duration - 0.001)).replace('<svg ', '<svg style="width:100%;height:100%;display:block" preserveAspectRatio="xMidYMid slice" ');
  };
  const t0 = performance.now();
  const tick = (n) => {
    const t = (n - t0) / 1000;
    draw(t);
    if (t < S.duration) raf = requestAnimationFrame(tick); else close(false);
  };
  draw(0);
  raf = requestAnimationFrame(tick);
})();
"""
open("apps/web/public/intro/intro.js", "w", encoding="utf-8").write(head + engine + tail)
print("ok", len(engine))
