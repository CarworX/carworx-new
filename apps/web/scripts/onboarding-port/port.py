# Usage: python3 apps/web/scripts/onboarding-port/port.py <preview dist dir> apps/web
# The preview dist is planning/sites-customer-preview/dist on #83 @ b88a8ca.
# Ports the onboarding preview's styles into apps/web verbatim:
#   app/sites/onboarding/kit.css   the shared kit layer (questions, tiles,
#                                  chips, segment bar, listing card, nav).
#   app/sites/onboarding/apply.css the application page's own styles,
#                                  scoped under .ob-apply.
# The app's Studio layer (styles/studio.css) already provides tokens and the
# cx- components, so tokens.css and studio.css are not copied. Re-run to
# regenerate from the preview.
import re, sys
P, OUT = sys.argv[1], sys.argv[2]
HEAD = "/* GENERATED by scripts/onboarding-port/port.py from the Sites preview\n * (#83 @ b88a8ca, onboarding/{src}). Do not edit by hand. */\n\n"

kit = open(f"{P}/onboarding/_shared/kit.css", encoding="utf-8").read()
# The global resets duplicate the app's base layer and Tailwind preflight.
start = kit.index("*,\n*::before")
end = kit.index("/* type (the Studio type utilities")
kit = kit[:start] + kit[end:]
assert "@font-face" not in kit
open(f"{OUT}/app/sites/onboarding/kit.css", "w", encoding="utf-8").write(HEAD.format(src="_shared/kit.css") + kit)


def blocks(css):
    """Split CSS into (prelude, body) top-level blocks."""
    out, i, n = [], 0, len(css)
    while i < n:
        j = css.find("{", i)
        if j < 0:
            break
        depth, k = 1, j + 1
        while depth:
            depth += {"{": 1, "}": -1}.get(css[k], 0)
            k += 1
        out.append((css[i:j].strip(), css[j + 1 : k - 1]))
        i = k
    return out


def scope(css, prefix):
    res = []
    for pre, body in blocks(css):
        pre = re.sub(r"/\*.*?\*/", "", pre, flags=re.S).strip()
        if pre.startswith("@keyframes"):
            res.append(f"{pre} {{{body}}}")
        elif pre.startswith("@media"):
            res.append(f"{pre} {{\n{scope(body, prefix)}\n}}")
        else:
            sels = [s.strip() for s in pre.split(",")]
            res.append(", ".join(f"{prefix} {s}" for s in sels) + f" {{{body.strip()} }}")
    return "\n".join(res)


h = open(f"{P}/onboarding/phase1/index.html", encoding="utf-8").read()
style = re.search(r"<style>(.*?)</style>", h, flags=re.S).group(1)
# ?rail=off was the owner's desktop A/B; the app has the rail.
style = re.sub(r"\s*/\* \?rail=off.*?\*/\s*\.norail[^\n]*\n\s*\.norail[^\n]*\n", "\n", style, flags=re.S)
assert ".norail" not in style
style = style.replace("rise", "ob-rise")
open(f"{OUT}/app/sites/onboarding/apply.css", "w", encoding="utf-8").write(
    HEAD.format(src="phase1/index.html") + scope(style, ".ob-apply") + "\n"
)
print("ok")
