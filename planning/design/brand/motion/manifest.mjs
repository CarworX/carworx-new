// Writes ../MANIFEST.md: every exported file with size and checksum, tool versions and check results.
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { join, relative } from 'node:path';
import { FFMPEG } from './render.mjs';

const EX = '../exports';
const walk = (d) => readdirSync(d).flatMap((f) => (statSync(join(d, f)).isDirectory() ? walk(join(d, f)) : [join(d, f)]));
const files = walk(EX).filter((f) => !/files\.json$|verify\.json$/.test(f)).sort();
const notes = Object.fromEntries(JSON.parse(readFileSync(`${EX}/files.json`, 'utf8')).files.map((f) => [f.path, f.note]));
const contrast = JSON.parse(readFileSync(`${EX}/files.json`, 'utf8')).contrast;
const V = JSON.parse(readFileSync(`${EX}/verify.json`, 'utf8'));
const pkg = (n) => JSON.parse(readFileSync(`node_modules/${n}/package.json`, 'utf8')).version;
const ffv = String(spawnSync(FFMPEG, ['-version']).stdout).split('\n')[0];
const kb = (b) => (b < 1024 * 1024 ? `${(b / 1024).toFixed(1)} KB` : `${(b / 1048576).toFixed(2)} MB`);

let md = `# CarworX Turbine: asset manifest

Generated by \`motion/manifest.mjs\` on ${new Date().toISOString().slice(0, 10)}. Every file below is generated from \`motion/shape.mjs\` (mark geometry), \`motion/geometry.mjs\` (wordmark and lockups) and \`motion/timeline.mjs\` (motion).

## Sources and licences

| Item | Source | Licence |
|---|---|---|
| Mark geometry, timeline, all artwork | This repo, \`planning/design/brand/motion/\` | CarworX |
| Wordmark letterforms (outlined, respaced; custom X) | Sora SemiBold 600, Fontsource static build of the Sora Project font, \`motion/fonts/Sora-SemiBold.ttf\` | SIL Open Font Licence 1.1 (\`motion/fonts/OFL.txt\`) |
| Audio | None | n/a |

## Tools

| Tool | Version |
|---|---|
| Node.js | ${process.version} |
| @resvg/resvg-js (SVG rasteriser) | ${pkg('@resvg/resvg-js')} |
| opentype.js (font outlines) | ${pkg('opentype.js')} |
| ffmpeg-static | ${pkg('ffmpeg-static')} (${ffv.replace(/ Copyright.*/, '')}) |
| ffprobe-static | ${pkg('ffprobe-static')} |

## Checks

| Check | Result |
|---|---|
| Determinism: frames rendered twice (second pass reversed), decoded RGBA compared | ${V.determinism.map((d) => `${d.cut} ${d.fmt}: ${d.identical ? 'PASSED' : 'FAILED'} (${d.times.join(', ')} s)`).join('<br>')} |
| Last frame of each hero film equals the still lockup | ${V.finalFrame.map((f) => `${f.fmt}: ${f.maxChannelDelta === 0 ? 'PASSED, identical' : `FAILED, max delta ${f.maxChannelDelta}`}`).join('<br>')} |
| Loop seam (last vs first frame of the loop) | max channel delta ${V.loopSeam.maxChannelDelta}/255: ${V.loopSeam.maxChannelDelta <= 3 ? 'PASSED' : 'FAILED'} |
| Contrast of approved pairs (WCAG) | ${contrast.map((c) => `${c.pair} ${c.ratio}:1`).join('<br>')} |
| Contact sheets across full duration and transition frames | Inspected by eye during production (hero 16:9, 1:1, 9:16, splash, loop seam) |
| Stills at real size (icons, favicons 16/32/48, social, print) | Inspected by eye |
| Playback at normal speed | PASSED: \`carworx-hero-16x9.mp4\` played in Chromium (built-in browser): 2.97 s of video in 3 s, 1920×1080, 8 s. The live preview advanced 2.38 s in 2 s at about 106 fps. The other films are checked by ffprobe only. |
| Real-device icon masks, print colour, sound | UNVERIFIED (no devices, no proof, no audio track) |

## Motion files (ffprobe)

| File | Codec | Size | fps | Pixel format | Duration | Audio | Bytes |
|---|---|---|---|---|---|---|---|
${Object.entries(V.probe).map(([f, p]) => `| \`motion/${f}\` | ${p.codec} | ${p.size} | ${p.fps} | ${p.pix_fmt} | ${p.duration ?? 'n/a'} s | ${p.audio ? 'yes' : 'none'} | ${kb(p.bytes)} |`).join('\n')}

## All files

| File | Use | Size | SHA-256 (first 16) |
|---|---|---|---|
${files.map((f) => {
  const rel = relative(EX, f).replace(/\\/g, '/');
  const buf = readFileSync(f);
  return `| \`${rel}\` | ${notes[rel] ?? (rel.startsWith('motion/') ? 'Motion' : '')} | ${kb(buf.length)} | \`${createHash('sha256').update(buf).digest('hex').slice(0, 16)}\` |`;
}).join('\n')}
`;
writeFileSync('../MANIFEST.md', md);
console.log('MANIFEST.md', files.length, 'files');
